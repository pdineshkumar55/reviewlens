"""Checks applied to text that end users will see.

Two lists live here so the output sanitizer and the UI copy check share them:

* ``BANNED_UI_WORDS``  - words that must not appear in any UI string (rule 0.1).
* ``STYLE_PHRASES``    - hype words and chatty openers/closers (rule 0.2).

``BANNED_OUTPUT`` covers self-references that must never appear in summaries,
replies or report text produced by the classifier and report chains.
"""

from __future__ import annotations

import re

BANNED_UI_WORDS: list[str] = [
    "AI",
    "A.I.",
    "artificial intelligence",
    "LLM",
    "language model",
    "model",
    "models",
    "GPT",
    "OpenAI",
    "ChatGPT",
    "Claude",
    "Anthropic",
    "Gemini",
    "LangChain",
    "prompt",
    "prompts",
    "token",
    "tokens",
    "agent",
    "agents",
    "bot",
    "chatbot",
    "assistant",
    "generated",
    "generative",
    "neural",
    "machine learning",
    "ML",
    "intelligent",
    "smart",
    "magic",
]

BANNED_ICONS: list[str] = ["\U0001f916", "\U0001f9e0", "✨", "\U0001fa84"]  # robot, brain, sparkles, wand

STYLE_PHRASES: list[str] = [
    "unlock",
    "unleash",
    "seamless",
    "seamlessly",
    "effortless",
    "effortlessly",
    "elevate",
    "supercharge",
    "empower",
    "harness",
    "leverage",
    "dive into",
    "delve",
    "game-changer",
    "game changer",
    "revolutionize",
    "revolutionise",
    "cutting-edge",
    "robust",
    "comprehensive insights",
    "powerful insights",
    "in today's fast-paced world",
    "journey",
    "certainly!",
    "great question",
    "here's",
    "let's",
    "i hope this helps",
    "feel free to",
]

BANNED_OUTPUT: list[str] = [
    r"\bas an ai\b",
    r"\ban ai\b",
    r"\bartificial intelligence\b",
    r"\blanguage model\b",
    r"\bi am an? (ai|assistant|bot|chatbot|model)\b",
    r"\bi'm an? (ai|assistant|bot|chatbot|model)\b",
    r"\b(virtual|digital|ai) assistant\b",
    r"\bchatgpt\b",
    r"\bopenai\b",
    r"\bclaude\b",
    r"\banthropic\b",
    r"\bgpt-?\d",
    r"\bllm\b",
    r"\bgenerated by\b",
]


def _phrase_pattern(phrase: str) -> re.Pattern[str]:
    # Word boundaries only where the phrase starts/ends with a word character,
    # so entries like "A.I." and "certainly!" still match.
    start = r"\b" if phrase[0].isalnum() else ""
    end = r"\b" if phrase[-1].isalnum() else ""
    return re.compile(start + re.escape(phrase) + end, re.IGNORECASE)


_OUTPUT_RE = [re.compile(p, re.IGNORECASE) for p in BANNED_OUTPUT]
_STYLE_RE = [(p, _phrase_pattern(p)) for p in STYLE_PHRASES]
_UI_RE = [(w, _phrase_pattern(w)) for w in BANNED_UI_WORDS]


def _normalise_quotes(text: str) -> str:
    return text.replace("’", "'").replace("‘", "'")


def find_self_references(text: str) -> list[str]:
    text = _normalise_quotes(text or "")
    return [m.group(0) for rx in _OUTPUT_RE if (m := rx.search(text))]


def find_style_phrases(text: str) -> list[str]:
    text = _normalise_quotes(text or "")
    return [phrase for phrase, rx in _STYLE_RE if rx.search(text)]


def find_banned_ui_words(text: str) -> list[str]:
    hits = [word for word, rx in _UI_RE if rx.search(text or "")]
    hits += [icon for icon in BANNED_ICONS if icon in (text or "")]
    return hits


def output_problems(text: str) -> list[str]:
    """All reasons a piece of user-facing output should be rejected."""
    problems = [f"self-reference '{h}'" for h in find_self_references(text)]
    problems += [f"style phrase '{h}'" for h in find_style_phrases(text)]
    return problems


def check_output(text: str) -> None:
    """Raise ValueError if text contains self-references or AI-style phrasing."""
    problems = output_problems(text)
    if problems:
        raise ValueError("Output contains disallowed wording: " + ", ".join(problems))
